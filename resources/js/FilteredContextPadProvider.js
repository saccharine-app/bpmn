import { getAllowedActionIds } from './engineCapabilities.js';

/**
 * Context Pad filter middleware.
 * Intercepts default context pad entries (append, delete, connect, replace)
 * and only trims append actions for unsupported elements.
 */
export default class FilteredContextPadProvider {
    constructor(contextPad, elementFactory, autoPlace, create) {
        this._elementFactory = elementFactory;
        this._autoPlace = autoPlace;
        this._create = create;

        contextPad.registerProvider(this);
    }

    getContextPadEntries(element) {
        const allowedAppendActions = getAllowedActionIds('contextPad');
        const { _elementFactory: elementFactory, _autoPlace: autoPlace, _create: create } = this;

        return function(entries) {
            // Remove append entries generated by default that aren't allowed
            Object.keys(entries).forEach(key => {
                if (key.startsWith('append.') && !allowedAppendActions.has(key)) {
                    delete entries[key];
                }
            });

            // Fallback: If default bpmn-js did not natively render an append entry
            // that is supported (e.g. ServiceTask or UserTask direct append),
            // ensure it is present on all non-EndEvent shapes.
            if (element.type !== 'bpmn:EndEvent') {
                if (allowedAppendActions.has('append.service-task') && !entries['append.service-task']) {
                    entries['append.service-task'] = createAppendEntry(
                        'bpmn:ServiceTask',
                        'bpmn-icon-service-task',
                        'Append Service Task',
                        elementFactory,
                        autoPlace,
                        create
                    );
                }

                if (allowedAppendActions.has('append.user-task') && !entries['append.user-task']) {
                    entries['append.user-task'] = createAppendEntry(
                        'bpmn:UserTask',
                        'bpmn-icon-user-task',
                        'Append User Task',
                        elementFactory,
                        autoPlace,
                        create
                    );
                }
            }

            return entries;
        };
    }
}

function createAppendEntry(type, className, title, elementFactory, autoPlace, create) {
    return {
        group: 'model',
        className: className,
        title: title,
        action: {
            dragstart: (event, element) => {
                const shape = elementFactory.createShape({ type });
                create.start(event, shape, { source: element });
            },
            click: (event, element) => {
                const shape = elementFactory.createShape({ type });
                autoPlace.append(element, shape);
            }
        }
    };
}

FilteredContextPadProvider.$inject = [
    'contextPad',
    'elementFactory',
    'autoPlace',
    'create'
];

export const FilteredContextPadModule = {
    __init__: ['filteredContextPadProvider'],
    filteredContextPadProvider: ['type', FilteredContextPadProvider]
};